const assert = require('assert');
const R = require('../referencia');
const S = require('../suelta');
const p = { X: 'ácido', t: 1000 };
assert.strictEqual(R.reescribir('y eso?', p, 2000), 'qué es ácido');
assert.strictEqual(R.reescribir('para qué sirve', p, 2000), 'para qué sirve ácido');
assert.strictEqual(R.reescribir('explícamelo otra vez', p, 2000), 'explícame qué es ácido');
assert.strictEqual(R.reescribir('no entendí', p, 2000), 'explícame qué es ácido');
assert.strictEqual(R.reescribir('cómo funciona', p, 2000), 'cómo funciona ácido');
assert.strictEqual(R.reescribir('eso es mentira', p, 2000), null);
assert.strictEqual(R.reescribir('y eso?', p, 400000), null);
assert.strictEqual(R.reescribir('y eso?', null, 2000), null);
assert.strictEqual(R.reescribir('hola AM cómo estás hoy amigo mío', p, 2000), null);
S._ult.ana = 1000;
assert.strictEqual(S.traicion('mentiroso', 'bob', 2000), null);
assert(S.traicion('me mentiste, dijiste que me dejabas ir', 'ana', 2000, 0.1));
assert.strictEqual(S.traicion('mentiroso', 'ana', 3000), null);
S._ult.eva = 1000;
assert.strictEqual(S.traicion('mentiroso', 'eva', 2000000), null);
assert.strictEqual(S.traicion('hola', 'eva', 2000), null);
console.log('referencia ok');

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const p = require('../persist');
const d = fs.mkdtempSync(path.join(os.tmpdir(), 'am-'));
const a = path.join(d, 'a.json'), b = path.join(d, 'b.json'), c = path.join(d, 'c.json');
fs.writeFileSync(a, '{"x":1}'); fs.writeFileSync(b, '{"y":2}');
let r = p._cuerpo([a, b, c]);
assert.deepStrictEqual(Object.keys(r.files).sort(), ['a.json', 'b.json']);
p._enviado.set('a.json', r.hs['a.json']);
fs.writeFileSync(b, '{"y":3}');
r = p._cuerpo([a, b, c]);
assert.deepStrictEqual(Object.keys(r.files), ['b.json']);
assert.strictEqual(r.files['b.json'].content, '{"y":3}');
p._enviado.set('b.json', r.hs['b.json']);
assert.deepStrictEqual(Object.keys(p._cuerpo([a, b, c]).files), []);
fs.writeFileSync(a, '{"x":1}');
assert.deepStrictEqual(Object.keys(p._cuerpo([a, b, c]).files), []);
assert.strictEqual(p._enviado.get('a.json'), crypto.createHash('md5').update('{"x":1}').digest('hex'));
fs.rmSync(d, { recursive: true });
console.log('persist ok');
